CREATE TABLE OfertaCobro (
    id_oferta_cobro BIGINT NOT NULL AUTO_INCREMENT,
    id_matricula BIGINT NOT NULL,
    id_concepto_cobro BIGINT NOT NULL,
    concepto_nombre VARCHAR(160) NOT NULL,
    referencia VARCHAR(80) NOT NULL,
    clave_oferta VARCHAR(64) NOT NULL,
    titulo VARCHAR(160) NOT NULL,
    descripcion VARCHAR(600),
    monto_base DECIMAL(12,2) NOT NULL,
    descuento_aceptado DECIMAL(12,2),
    monto_aceptado DECIMAL(12,2),
    beneficio_aceptado VARCHAR(160),
    fecha_vencimiento DATE NOT NULL,
    fecha_limite_aceptacion DATE NOT NULL,
    estado VARCHAR(20) NOT NULL,
    id_compromiso_pago BIGINT,
    id_apoderado_respuesta BIGINT,
    respondida_en TIMESTAMP(6),
    motivo_respuesta VARCHAR(500),
    fecha_creacion TIMESTAMP(6) NOT NULL,
    fecha_actualizacion TIMESTAMP(6) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id_oferta_cobro),
    CONSTRAINT uk_oferta_cobro_clave UNIQUE (clave_oferta),
    CONSTRAINT uk_oferta_cobro_compromiso UNIQUE (id_compromiso_pago),
    CONSTRAINT fk_oferta_cobro_matricula FOREIGN KEY (id_matricula) REFERENCES Matricula(id_matricula),
    CONSTRAINT fk_oferta_cobro_concepto FOREIGN KEY (id_concepto_cobro) REFERENCES ConceptoCobro(id_concepto_cobro),
    CONSTRAINT fk_oferta_cobro_compromiso FOREIGN KEY (id_compromiso_pago) REFERENCES CompromisoPago(id_compromiso_pago),
    CONSTRAINT fk_oferta_cobro_apoderado FOREIGN KEY (id_apoderado_respuesta) REFERENCES Apoderado(id_apoderado)
);
CREATE INDEX idx_oferta_cobro_matricula ON OfertaCobro(id_matricula, estado);
